#!/usr/bin/env python3
"""Check platform-specific settings in the generated Projucer project."""
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

project = Path('Quetzalcoatl/Quetzalcoatl/Binaries/AutogeneratedProject.jucer')
with tempfile.TemporaryDirectory() as d:
    root = Path(d)
    hise = root / 'HISE'
    (hise / 'hi_core').mkdir(parents=True)
    sdk = hise / 'JUCE/modules/juce_audio_processors/format_types/VST3_SDK/pluginterfaces/vst'
    sdk.mkdir(parents=True)
    (sdk / 'vsttypes.h').touch()
    for platform in ('macos', 'windows', 'linux'):
        output = root / f'{platform}.jucer'
        shutil.copyfile(project, output)
        subprocess.run([sys.executable, 'scripts/prepare_export_project.py', str(output), str(hise), platform], check=True)
        tree = ET.parse(output).getroot()
        assert tree.get('buildVST3') == '1'
        assert tree.get('buildAU') == ('1' if platform == 'macos' else '0')
        assert tree.find('JUCEOPTIONS').get('HISE_USE_SYSTEM_APP_DATA_FOLDER') == ('1' if platform == 'windows' else '0')
        assert all(c.get('osxArchitecture') == '64BitUniversal' for c in tree.findall('./EXPORTFORMATS/XCODE_MAC/CONFIGURATIONS/CONFIGURATION'))
print('Export settings verified on macOS, Windows and Linux')
